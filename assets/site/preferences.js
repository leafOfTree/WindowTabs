const languages = {en:'English', zh:'简体中文', ja:'日本語', ar:'العربية', ko:'한국어'};
const translationOrder = ['zh', 'ja', 'ko', 'ar'];
let language;
function translate(key) {
  return translations[key]?.[translationOrder.indexOf(language)] ?? key;
}

const page = document.getElementById('wt-claude');
const textEntries = [];
const walker = document.createTreeWalker(page, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const node = walker.currentNode;
  const original = node.data;
  const key = original.trim();
  if (Object.hasOwn(translations, key)) textEntries.push({node, original, key});
}
const labels = Array.from(page.querySelectorAll('[aria-label]'), el => [el, el.ariaLabel]);
const illustrationKeys = ['Bring related windows together','Switch with familiar tabs','Work side by side','Auto-group new windows','Keep apps together by rule','Restore a familiar layout'];
const illustrationLabels = Array.from(page.querySelectorAll('.core-illustrations img,.concept-art img'), img => [img,img.alt]);
const description = document.querySelector('meta[name="description"]');
const originalDescription = description.content;
const descriptions = {zh:'将桌面窗口归组为标签页，并排工作，随时恢复工作区布局。',ja:'デスクトップのウィンドウをタブにまとめ、並べて作業し、いつもの配置を保存できます。',ko:'데스크톱 창을 탭으로 묶고 나란히 작업하며 익숙한 배치를 저장하세요.',ar:'اجمع نوافذ سطح المكتب في تبويبات واعمل جنبًا إلى جنب واحفظ ترتيب نوافذك.'};

const themeSwitch = document.querySelector('#site-theme');
const languageSelect = document.querySelector('#site-language');
function applyTheme(dark) {
  document.documentElement.dataset.theme = dark ? 'dark' : 'light';
  themeSwitch.setAttribute('aria-checked', String(dark));
}
function applyLanguage() {
  language = languageSelect.value;
  if (language === 'auto') {
    language = [...(navigator.languages || []), navigator.language]
      .map(tag => tag?.split('-')[0].toLowerCase()).find(tag => Object.hasOwn(languages, tag)) || 'en';
  }
  document.querySelector('.language-short').textContent = {en:'EN', zh:'中', ja:'日', ko:'한', ar:'ع'}[language];
  document.documentElement.lang = language === 'zh' ? 'zh-Hans' : language;
  document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
  for (const {node, original, key} of textEntries) node.data = original.replace(key, translate(key));
  for (const [el, key] of labels) el.ariaLabel = translate(key);
  illustrationLabels.forEach(([img, original], i) => { img.alt = language === 'en' ? original : translate(illustrationKeys[i]); });
  document.title = 'WindowTabs — ' + translate('Browser-style tabs for your desktop windows');
  description.content = descriptions[language] || originalDescription;
  themeSwitch.title = translate('Dark mode');
  languageSelect.title = translate('Language');
  document.dispatchEvent(new Event('site-languagechange'));
}
try {
  const saved = localStorage.getItem(languageSelect.id);
  if ([...languageSelect.options].some(option => option.value === saved)) languageSelect.value = saved;
} catch { /* Storage may be disabled. */ }
languageSelect.addEventListener('change', () => {
  try { localStorage.setItem(languageSelect.id, languageSelect.value); } catch { /* Apply for this visit. */ }
  applyLanguage();
});
applyTheme(matchMedia('(prefers-color-scheme: dark)').matches);
applyLanguage();
themeSwitch.addEventListener('click', () => applyTheme(themeSwitch.getAttribute('aria-checked') !== 'true'));
window.addEventListener('languagechange', () => { if (languageSelect.value === 'auto') applyLanguage(); });
